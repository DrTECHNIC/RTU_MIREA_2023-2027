package com.vrazhenko.documentfeature;

import org.springframework.boot.CommandLineRunner;
import org.springframework.stereotype.Component;

import java.time.LocalDate;
import java.util.List;

@Component
public class DataInitializer implements CommandLineRunner {

    private final DocumentService documentService;

    public DataInitializer(DocumentService documentService) {
        this.documentService = documentService;
    }

    @Override
    public void run(String... args) throws Exception {
        if (documentService.findAllDocuments().isEmpty()) {
            createDoc("Приказ о приеме на работу", "100-01",
                    "Настоящий приказ подготовлен специалистом отдела кадров Враженко Даниилом Олеговичем. " +
                            "Принять на должность инженера-программиста с испытательным сроком три месяца. " +
                            "Основание: заявление сотрудника. Контроль за исполнением оставляю за собой.");

            createDoc("Распоряжение об отпуске", "100-02",
                    "В соответствии с изданными ранее приказами руководства компании, предоставить ежегодный оплачиваемый отпуск. " +
                            "Срок отпуска составляет 14 календарных дней. Бухгалтерии произвести соответствующие начисления. " +
                            "Настоящее распоряжение довести до сведения всех заинтересованных лиц.");

            createDoc("Служебная записка", "100-03",
                    "В целях исполнения приказа генерального директора от первого числа текущего месяца, " +
                            "прошу выделить дополнительные ресурсы для отдела разработки. " +
                            "В настоящее время наблюдается острая нехватка вычислительной техники. " +
                            "Ожидаемый эффект позволит ускорить выпуск релиза.");

            createDoc("Приказ о премировании", "100-04",
                    "За успешное выполнение плановых показателей объявить благодарность сотрудникам. " +
                            "В данном приказе особо отмечается вклад Враженко Даниила Олеговича в реализацию проекта. " +
                            "Выплатить единовременную премию. Отделу кадров ознакомить сотрудников с данным приказом под роспись.");

            createDoc("Регламент работы", "100-05",
                    "Настоящий документ описывает порядок разработки внутренних приказов и распоряжений. " +
                            "Все проекты приказов должны проходить обязательное согласование с юридическим отделом. " +
                            "После согласования документ направляется на подпись руководителю. " +
                            "Несоблюдение регламента влечет за собой дисциплинарную ответственность.");

            createDoc("Акт проверки", "100-06",
                    "В ходе плановой проверки было установлено, что ранее изданные приказы по охране труда " +
                            "выполняются не в полном объеме. Выявлены нарушения сроков проведения инструктажей. " +
                            "Предписано устранить замечания в течение десяти рабочих дней с момента получения акта.");

            createDoc("Отчет о работе", "100-07",
                    "За отчетный период была проведена работа по систематизации архива документов. " +
                            "Подготовлен перечень устаревших приказов для передачи в государственный архив. " +
                            "Опись документов составлена согласно установленным нормам. " +
                            "Ответственным лицом за подготовку отчета является Враженко Даниил Олегович.");

            System.out.println("Тестовые данные успешно загружены в БД и проиндексированы в OpenSearch.");
        }
    }

    private void createDoc(String title, String regNumber, String content) {
        Document doc = new Document();
        doc.setTitle(title);
        doc.setRegNumber(regNumber);
        doc.setRegDate(LocalDate.now());
        doc.setType("Приказ");
        doc.setUrgent(false);
        doc.setContent(content);

        documentService.saveDocument(doc);
    }
}
